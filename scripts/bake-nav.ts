/**
 * Bakes navigation data for every map definition and writes it next to the map assets:
 *   src/world/def/maps/nav/baked.generated.ts
 * Usage:  npm run nav:bake          regenerate
 *         npm run nav:check         fail (exit 1) if baked data is stale
 */
import { init } from '@recast-navigation/core';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import { MAP_DEFINITIONS } from '../src/world/def/maps';
import { compileMap, validateMapDefinition } from '../src/world/def/compile';
import { bakeNav, navHash, packBaked } from '../src/world/nav/bake';
import { BAKED_NAV } from '../src/world/def/maps/nav/baked.generated';

const here = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.resolve(here, '../src/world/def/maps/nav/baked.generated.ts');
const checkOnly = process.argv.includes('--check');

await init();
const table: Record<string, Record<string, string>> = {};
let stale = 0;
for (const def of Object.values(MAP_DEFINITIONS)) {
  const errors = validateMapDefinition(def);
  if (errors.length) {
    console.error(`[nav] ${def.id}: invalid map definition\n  ${errors.join('\n  ')}`);
    process.exit(1);
  }
  const compiled = compileMap(def);
  table[def.id] = {};
  for (const profile of def.nav.profiles) {
    const wantHash = navHash(compiled, profile);
    const existing = BAKED_NAV[def.id]?.[profile];
    const existingFresh = existing !== undefined && Buffer.from(existing, 'base64').toString('latin1', 9, 17) === wantHash;
    if (checkOnly) {
      if (!existingFresh) {
        stale++;
        console.error(`[nav] STALE ${def.id}/${profile} (want ${wantHash})`);
      }
      continue;
    }
    if (existingFresh) {
      table[def.id][profile] = existing;
      console.log(`[nav] ${def.id}/${profile} up to date (${wantHash})`);
      continue;
    }
    const baked = bakeNav(compiled, profile);
    table[def.id][profile] = Buffer.from(packBaked(baked)).toString('base64');
    console.log(`[nav] baked ${def.id}/${profile}: ${baked.stats.bytes} B, ${baked.stats.ms.toFixed(0)} ms, ${baked.hash}`);
  }
}
if (checkOnly) {
  if (stale) process.exit(1);
  console.log('[nav] all baked navigation data is fresh');
} else {
  const body = Object.entries(table)
    .map(([id, profiles]) => `  ${id}: {\n${Object.entries(profiles).map(([p, b64]) => `    ${p}: '${b64}',`).join('\n')}\n  },`)
    .join('\n');
  fs.writeFileSync(
    outFile,
    `// GENERATED by scripts/bake-nav.ts - do not edit. Regenerate with \`npm run nav:bake\`.\nexport const BAKED_NAV: Record<string, Partial<Record<string, string>>> = {\n${body}\n};\n`,
  );
  console.log(`[nav] wrote ${path.relative(process.cwd(), outFile)}`);
}
